import test from './helpers/postgres-context.js';
import assert from 'node:assert/strict';
import { join } from 'node:path';
import { runtimeFixture } from './helpers/runtime.js';
import { enableMfa } from './helpers/mfa.js';
import { DatabaseSync } from 'node:sqlite';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { create as archive } from '../dist/vendor/archive.js';
import { sha256File } from '../dist/shared/backup-contract.js';
test('restore preparation checks admin access and counts without touching the live database', async (t) => {
    const { prepareBackup } = await import('../dist/server/backup-restore.js');
    const f = await runtimeFixture(t);
    await f.setup();
    const p = await f.app.store.createProduct({ name: 'Gesichert', sku: 'A' });
    await f.app.store.createReturn({ productId: p.id, serialNumber: 'SN' });
    const backup = await f.app.backups.create({ id: null, name: 'Test', source: 'system' });
    const summary = await prepareBackup({ databaseConfig: f.databaseConfig, archive: join(f.dataDir, 'backups', backup.filename), target: join(f.dataDir, 'prepared') });
    assert.equal(summary.products, 1);
    assert.equal(summary.returns, 1);
    assert.equal(summary.administratorAccess, true);
    assert.equal(summary.attachments, 0);
    assert.equal((await f.app.store.listProducts()).length, 1);
    await assert.rejects(async () => prepareBackup({ databaseConfig: f.databaseConfig, archive: join(f.dataDir, 'backups', backup.filename), target: join(f.dataDir, 'too-big'), limits: { maxArchiveBytes: 1, maxFileBytes: 1, maxTotalBytes: 1, maxFiles: 1 } }));
});
test('MFA access preview needs a matching key and cannot mistake forced enrollment for access', async (t) => {
    const { prepareBackup } = await import('../dist/server/backup-restore.js'), now = Date.parse('2026-10-07T10:00:00Z'), f = await runtimeFixture(t, { now: () => now }), first = await f.setup();
    await enableMfa(f, first.auth, now);
    const saved = await f.app.backups.create({ id: 1, name: 'Admin', source: 'user' }), path = join(f.dataDir, 'backups', saved.filename);
    const without = await prepareBackup({ databaseConfig: f.databaseConfig, archive: path, target: join(f.dataDir, 'no-key') });
    assert.equal(without.administratorAccess, false);
    assert.equal(without.unavailableMfaAccounts, 1);
    const wrong = await prepareBackup({ databaseConfig: f.databaseConfig, archive: path, target: join(f.dataDir, 'wrong-key'), mfaKey: Buffer.alloc(32) });
    assert.equal(wrong.administratorAccess, false);
    const good = await prepareBackup({ databaseConfig: f.databaseConfig, archive: path, target: join(f.dataDir, 'good-key'), mfaKey: readFileSync(f.app.secrets.path('mfa')) });
    assert.equal(good.administratorAccess, true);
    await f.app.users.create({ username: 'ForceAdmin', role: 'admin', password: 'Testkonto-Passwort!' });
    await f.app.mfa.reset(2);
    await f.app.store.db.query("UPDATE users SET role='member' WHERE id=1", []);
    const forced = await f.app.backups.create({ id: 2, name: 'Admin', source: 'user' });
    const gate = await prepareBackup({ databaseConfig: f.databaseConfig, archive: join(f.dataDir, 'backups', forced.filename), target: join(f.dataDir, 'forced') });
    assert.equal(gate.administratorAccess, false);
});
test('archive preparation rejects incomplete SQLite schemas and duplicate members', async (t) => {
    const { prepareBackup } = await import('../dist/server/backup-restore.js'), f = await runtimeFixture(t);
    await f.setup();
    const dir = join(f.dataDir, 'bad-schema');
    mkdirSync(dir);
    const db = new DatabaseSync(join(dir, 'retouren.sqlite'));
    db.exec('CREATE TABLE unrelated(value TEXT)');
    db.close();
    const file = join(f.dataDir, 'schema.tar.gz');
    writeFileSync(join(dir, 'manifest.json'), JSON.stringify({ format: 1, database: 'retouren.sqlite', version: '1.4.2', files: [{ path: 'retouren.sqlite', size: readFileSync(join(dir, 'retouren.sqlite')).length, sha256: await sha256File(join(dir, 'retouren.sqlite')) }] }));
    await archive({ cwd: dir, file, gzip: true }, ['manifest.json', 'retouren.sqlite']);
    await assert.rejects(async () => prepareBackup({ databaseConfig: f.databaseConfig, archive: file, target: join(f.dataDir, 'schema-target') }), /vollständige/);
    await archive({ cwd: dir, file, gzip: true }, ['manifest.json', 'retouren.sqlite', 'retouren.sqlite']);
    await assert.rejects(async () => prepareBackup({ databaseConfig: f.databaseConfig, archive: file, target: join(f.dataDir, 'duplicate-target') }), /unzulässige/);
});
