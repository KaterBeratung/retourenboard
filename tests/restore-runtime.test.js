import test from './helpers/postgres-context.js';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
test('online restore replaces data, retains the safety backup and requires a new login', async (t) => {
    const { createRuntime } = await import('./helpers/postgres-fixtures.js'), dir = mkdtempSync(join(tmpdir(), 'retourenboard-restore-api-'));
    let runtime = await createRuntime({ dbPath: join(dir, 'preview.sqlite'), port: 0, host: '127.0.0.1' });
    t.after(async () => { await runtime.close(); rmSync(dir, { recursive: true, force: true }); });
    await runtime.start();
    const base = `http://127.0.0.1:${runtime.current().server.address().port}`;
    let auth = {};
    const request = async (path, method = 'GET', body, extra = {}) => fetch(base + path, { method, headers: { Origin: base, 'Content-Type': 'application/json', ...auth, ...extra }, body: body === undefined ? undefined : JSON.stringify(body) });
    const setup = await request('/api/setup', 'POST', { username: 'Admin', password: 'Testkonto-Passwort!' }), session = await setup.json();
    auth = { Cookie: setup.headers.get('set-cookie').split(';')[0], 'X-CSRF-Token': session.csrfToken };
    assert.equal((await request('/api/admin/backups/restore/prepare', 'POST', { backupId: 'bad' }, { 'X-CSRF-Token': 'bad' })).status, 403);
    const app = runtime.current();
    await app.store.createProduct({ name: 'Archiv', sku: 'A' });
    const archive = await app.backups.create({ id: 1, name: 'Admin', source: 'user' });
    await app.store.createProduct({ name: 'Später', sku: 'B' });
    const response = await request('/api/admin/backups/restore/prepare', 'POST', { backupId: archive.id });
    assert.equal(response.status, 201);
    const preview = await response.json();
    assert.equal(preview.summary.products, 1);
    assert.equal(preview.state, 'ready');
    assert.equal((await request(`/api/admin/backups/restore/${preview.id}/commit`, 'POST', { confirmed: true, password: 'wrong' })).status, 401);
    const commit = await request(`/api/admin/backups/restore/${preview.id}/commit`, 'POST', { confirmed: true, password: 'Testkonto-Passwort!' });
    assert.equal(commit.status, 202);
    await commit.json();
    await runtime.waitForRestore();
    assert.equal((await runtime.current().store.listProducts()).length, 1);
    assert.equal((await (await request('/api/session')).json()).unlocked, false);
    assert.equal((await request('/api/products')).status, 401);
    assert.equal((await runtime.current().backups.list()).filter(b => b.state === 'complete').length, 2);
    const login = await request('/api/login', 'POST', { username: 'Admin', password: 'Testkonto-Passwort!' });
    assert.equal(login.status, 200);
});
